// Regenerates src/components/ModelConfig/configs.js from the FAITH package's
// __models__ directory, so the built-in configs shown on the Model Config Files
// page can never drift from the source of truth.
//
//   node scripts/sync-model-configs.js           # rewrite from this repo
//   node scripts/sync-model-configs.js --check   # CI gate
//
// --check exits non-zero if the committed file is stale, without writing.
//
// The site lives at website/ inside the faith repo, so the source of truth is
// the enclosing checkout — no path to configure. --repo exists only to point
// the site at a different faith tree.

import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

// Resolve paths from this file, not the cwd, so the scripts work from anywhere.
const SITE = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const args = process.argv.slice(2);
const check = args.includes("--check");
const repoIdx = args.indexOf("--repo");
const repo = repoIdx === -1 ? resolve(SITE, "..") : resolve(args[repoIdx + 1]);

const MODELS = join(repo, "src/faith/__models__");
const OUT = join(SITE, "src/components/ModelConfig/configs.js");

if (!existsSync(MODELS)) {
  console.error(
    `No __models__ directory at ${MODELS}\n` +
      `Expected the site to live at website/ inside the faith repo, ` +
      `or pass --repo <path-to-faith-checkout>.`,
  );
  process.exit(2);
}

// Strip the Apache license header and the YAML document marker; keep the body
// verbatim, including `!from` tags, so the page shows exactly what ships.
const body = (file) =>
  readFileSync(file, "utf8")
    .split("\n")
    .filter((l) => !l.startsWith("#"))
    .join("\n")
    .replace(/^\s*---\s*\n/m, "")
    .trim();

const shared = (name) => body(join(MODELS, name));

const group = (dir) =>
  readdirSync(join(MODELS, dir))
    .filter((f) => f.endsWith(".yaml"))
    .sort()
    .map((f) => ({
      name: f.replace(/\.yaml$/, ""),
      yaml: body(join(MODELS, dir, f)),
    }));

const tpl = (fn, models) =>
  models
    .map(
      (m) =>
        `      ${fn}(\n        '${m.name}',\n        \`${m.yaml}\`,\n      ),`,
    )
    .join("\n");

const instruct = group("instruct");
const reasoning = group("reasoning");

const generated = `// @generated by scripts/sync-model-configs.js — do not edit by hand.
// Mirrors src/faith/__models__/ in this repo. \`!from\` lines pull shared
// engine/generation blocks from the two defaults files below.
// Regenerate with: npm run sync-configs
export const DEFAULTS = {
  engines: \`${shared("default_engines.yaml")}\`,
  generation: \`${shared("default_generation.yaml")}\`,
};

const m = (name, yaml) => ({id: \`instruct/\${name}\`, name, yaml});
const r = (name, yaml) => ({id: \`reasoning/\${name}\`, name, yaml});

export const GROUPS = [
  {
    id: 'instruct',
    label: 'Instruct',
    models: [
${tpl("m", instruct)}
    ],
  },
  {
    id: 'reasoning',
    label: 'Reasoning',
    models: [
${tpl("r", reasoning)}
    ],
  },
];
`;

const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";

if (check) {
  if (current !== generated) {
    console.error(
      `configs.js is out of sync with ${MODELS}.\n` +
        `Run: node scripts/sync-model-configs.js --repo ${repo}`,
    );
    process.exit(1);
  }
  console.log(
    `configs.js in sync (${instruct.length} instruct, ${reasoning.length} reasoning).`,
  );
} else {
  writeFileSync(OUT, generated);
  console.log(
    `Wrote ${OUT} — ${instruct.length} instruct, ${reasoning.length} reasoning.`,
  );
}
